class TestLineagePipelineForwardBackward(unittest.TestCase):

    def test_multi_row_formula_to_select_unknown_checked_and_unchecked(self):
        """
        Verify that a column generated by MultiRowFormulaNode:
        1) Flows forward to Select when *Unknown is checked (keep=True).
        2) Is dropped by Select when *Unknown is unchecked (keep=False).
        3) Backward impact analysis correctly identifies kept vs dropped state.
        4) Physical node execution respects the *Unknown flag on generated columns.
        """
        # Workflow: src -> mrf -> sel
        workflow_unknown_checked = {
            "nodes": [
                {
                    "id": "src",
                    "name": "Input Sales",
                    "type": "input_data",
                    "config": {"columns": ["Date", "Amount"]}
                },
                {
                    "id": "mrf",
                    "name": "Running Total",
                    "type": "multi_row_formula",
                    "config": {
                        "is_new_field": True,
                        "output_field": "CumAmount",
                        "output_type": "float",
                        "expression": "[Row-1:CumAmount] + [Amount]"
                    }
                },
                {
                    "id": "sel",
                    "name": "Select Tool",
                    "type": "select",
                    "config": {
                        "fields": [
                            {"original": "Date", "keep": True, "rename": "Date"},
                            {"original": "Amount", "keep": True, "rename": "Amount"},
                            {"original": "*Unknown", "keep": True, "rename": "*Unknown"}
                        ]
                    }
                }
            ],
            "connections": [
                {"source": "src", "target": "mrf"},
                {"source": "mrf", "target": "sel"}
            ]
        }

        # 1. Forward lineage with *Unknown checked
        rich_checked = compute_rich_lineage(workflow_unknown_checked)
        self.assertIn("CumAmount", rich_checked["mrf"])
        self.assertEqual(rich_checked["mrf"]["CumAmount"]["category"], "calculated")
        self.assertIn(("src", "Amount"), rich_checked["mrf"]["CumAmount"]["sources"])

        # CumAmount should pass through to Select because *Unknown is checked
        self.assertIn("CumAmount", rich_checked["sel"])
        self.assertIn(("src", "Amount"), rich_checked["sel"]["CumAmount"]["sources"])

        # Backward impact with *Unknown checked
        impact_checked = compute_downstream_impact(workflow_unknown_checked, "mrf", "CumAmount")
        self.assertIn("sel", impact_checked["impacted_node_ids"])
        usages_checked = impact_checked["columns"]["CumAmount"]
        self.assertTrue(any("Dynamic" in u["usage"] or "Selected" in u["usage"] for u in usages_checked))

        # 2. Workflow with *Unknown unchecked
        workflow_unknown_unchecked = {
            "nodes": [
                {
                    "id": "src",
                    "name": "Input Sales",
                    "type": "input_data",
                    "config": {"columns": ["Date", "Amount"]}
                },
                {
                    "id": "mrf",
                    "name": "Running Total",
                    "type": "multi_row_formula",
                    "config": {
                        "is_new_field": True,
                        "output_field": "CumAmount",
                        "output_type": "float",
                        "expression": "[Row-1:CumAmount] + [Amount]"
                    }
                },
                {
                    "id": "sel",
                    "name": "Select Tool",
                    "type": "select",
                    "config": {
                        "fields": [
                            {"original": "Date", "keep": True, "rename": "Date"},
                            {"original": "Amount", "keep": True, "rename": "Amount"},
                            {"original": "*Unknown", "keep": False, "rename": "*Unknown"}
                        ]
                    }
                }
            ],
            "connections": [
                {"source": "src", "target": "mrf"},
                {"source": "mrf", "target": "sel"}
            ]
        }

        rich_unchecked = compute_rich_lineage(workflow_unknown_unchecked)
        self.assertIn("CumAmount", rich_unchecked["mrf"])
        # CumAmount must NOT be present in Select output when *Unknown is unchecked
        self.assertNotIn("CumAmount", rich_unchecked["sel"])
        self.assertIn("Date", rich_unchecked["sel"])
        self.assertIn("Amount", rich_unchecked["sel"])

        # Backward impact with *Unknown unchecked
        impact_unchecked = compute_downstream_impact(workflow_unknown_unchecked, "mrf", "CumAmount")
        self.assertIn("sel", impact_unchecked["impacted_node_ids"])
        usages_unchecked = impact_unchecked["columns"]["CumAmount"]
        self.assertTrue(any("Dropped in Select" in u["usage"] for u in usages_unchecked))

        # 3. Physical Node Execution test
        df_in = pd.DataFrame({"Date": ["2026-01-01", "2026-01-02", "2026-01-03"], "Amount": [10.0, 20.0, 30.0]})
        mrf_node = MultiRowFormulaNode("mrf", workflow_unknown_checked["nodes"][1]["config"])
        mrf_out = mrf_node.execute({"I": df_in}, {})["O"]
        self.assertIn("CumAmount", mrf_out.columns)
        self.assertEqual(list(mrf_out["CumAmount"]), [10.0, 30.0, 60.0])

        # Execute Select with *Unknown checked
        sel_node_checked = SelectNode("sel", workflow_unknown_checked["nodes"][2]["config"])
        sel_out_checked = sel_node_checked.execute({"I": mrf_out}, {})["O"]
        self.assertIn("CumAmount", sel_out_checked.columns)

        # Execute Select with *Unknown unchecked
        sel_node_unchecked = SelectNode("sel", workflow_unknown_unchecked["nodes"][2]["config"])
        sel_out_unchecked = sel_node_unchecked.execute({"I": mrf_out}, {})["O"]
        self.assertNotIn("CumAmount", sel_out_unchecked.columns)
        self.assertEqual(list(sel_out_unchecked.columns), ["Date", "Amount"])

    def test_multi_field_formula_to_select_lineage(self):
        """Verify Multi-Field Formula generates new prefix/suffix columns traced to source in Select."""
        workflow = {
            "nodes": [
                {
                    "id": "in1",
                    "name": "Input",
                    "type": "input_data",
                    "config": {"columns": ["Cost", "Tax"]}
                },
                {
                    "id": "mff",
                    "name": "Multi-Field",
                    "type": "multi_field_formula",
                    "config": {
                        "selected_fields": ["Cost", "Tax"],
                        "output_mode": "create_new",
                        "output_prefix": "Adj_",
                        "expression": "[_CurrentField_] * 1.15"
                    }
                },
                {
                    "id": "sel",
                    "name": "Select",
                    "type": "select",
                    "config": {
                        "fields": [
                            {"original": "Cost", "keep": False},
                            {"original": "Tax", "keep": False},
                            {"original": "Adj_Cost", "keep": True, "rename": "Adjusted_Cost"},
                            {"original": "*Unknown", "keep": True}
                        ]
                    }
                }
            ],
            "connections": [
                {"source": "in1", "target": "mff"},
                {"source": "mff", "target": "sel"}
            ]
        }

        rich = compute_rich_lineage(workflow)
        self.assertIn("Adj_Cost", rich["mff"])
        self.assertIn("Adj_Tax", rich["mff"])
        self.assertEqual(rich["mff"]["Adj_Cost"]["sources"], [("in1", "Cost")])
        self.assertEqual(rich["mff"]["Adj_Tax"]["sources"], [("in1", "Tax")])

        # Select renames Adj_Cost -> Adjusted_Cost, drops Cost/Tax, keeps Adj_Tax via *Unknown
        self.assertIn("Adjusted_Cost", rich["sel"])
        self.assertIn("Adj_Tax", rich["sel"])
        self.assertNotIn("Cost", rich["sel"])
        self.assertNotIn("Tax", rich["sel"])
        self.assertEqual(rich["sel"]["Adjusted_Cost"]["sources"], [("in1", "Cost")])
        self.assertEqual(rich["sel"]["Adj_Tax"]["sources"], [("in1", "Tax")])

        # Downstream impact of Cost
        impact = compute_downstream_impact(workflow, "in1", "Cost")
        self.assertIn("mff", impact["impacted_node_ids"])
        self.assertIn("sel", impact["impacted_node_ids"])
        usages = impact["columns"]["Cost"]
        self.assertTrue(any(u["node_id"] == "mff" for u in usages))
        self.assertTrue(any(u["node_id"] == "sel" and "Dropped" in u["usage"] for u in usages))

    def test_datetime_and_date_time_alias_lineage(self):
        """Verify DateTimeNode handles both 'date_time' and 'datetime' types with output field forwarding."""
        for ntype in ("datetime", "date_time"):
            workflow = {
                "nodes": [
                    {
                        "id": "src",
                        "name": "Input",
                        "type": "input_data",
                        "config": {"columns": ["RawDate", "User"]}
                    },
                    {
                        "id": "dt",
                        "name": "Date Converter",
                        "type": ntype,
                        "config": {
                            "column": "RawDate",
                            "output_column": "StandardDate",
                            "conversion_type": "string_to_date"
                        }
                    },
                    {
                        "id": "sel",
                        "name": "Select",
                        "type": "select",
                        "config": {
                            "fields": [
                                {"original": "StandardDate", "keep": True, "rename": "EventDate"},
                                {"original": "*Unknown", "keep": False}
                            ]
                        }
                    }
                ],
                "connections": [
                    {"source": "src", "target": "dt"},
                    {"source": "dt", "target": "sel"}
                ]
            }

            rich = compute_rich_lineage(workflow)
            self.assertIn("StandardDate", rich["dt"], f"Failed for {ntype}")
            self.assertEqual(rich["dt"]["StandardDate"]["sources"], [("src", "RawDate")])
            self.assertIn("EventDate", rich["sel"], f"Failed for {ntype}")
            self.assertEqual(rich["sel"]["EventDate"]["sources"], [("src", "RawDate")])

            impact = compute_downstream_impact(workflow, "src", "RawDate")
            self.assertIn("dt", impact["impacted_node_ids"])
            dt_usage = next(u for u in impact["columns"]["RawDate"] if u["node_id"] == "dt")
            self.assertIn("DateTime", dt_usage["usage"])

    def test_join_with_embedded_select_and_collisions(self):
        """Verify Join tool handles dual inputs, column collisions (Right_), and embedded select_fields."""
        workflow = {
            "nodes": [
                {
                    "id": "l_in",
                    "name": "Left Data",
                    "type": "input_data",
                    "config": {"columns": ["ID", "Name", "Dept"]}
                },
                {
                    "id": "r_in",
                    "name": "Right Data",
                    "type": "input_data",
                    "config": {"columns": ["ID", "Name", "Salary"]}
                },
                {
                    "id": "j",
                    "name": "Join",
                    "type": "join",
                    "config": {
                        "join_keys": [{"left_key": "ID", "right_key": "ID"}],
                        "select_fields": [
                            {"field": "ID", "source": "L", "keep": True, "rename": "EmpID"},
                            {"field": "Name", "source": "L", "keep": True, "rename": "EmpName"},
                            {"field": "Right_Name", "source": "R", "keep": False},
                            {"field": "Salary", "source": "R", "keep": True, "rename": "AnnualSalary"},
                            {"field": "*Unknown", "keep": False}
                        ]
                    }
                }
            ],
            "connections": [
                {"source": "l_in", "target": "j", "targetHandle": "L"},
                {"source": "r_in", "target": "j", "targetHandle": "R"}
            ]
        }

        rich = compute_rich_lineage(workflow)
        j_cols = rich["j"]
        self.assertIn("EmpID", j_cols)
        self.assertIn("EmpName", j_cols)
        self.assertIn("AnnualSalary", j_cols)
        self.assertNotIn("Right_Name", j_cols)
        self.assertNotIn("Dept", j_cols)  # Dropped because *Unknown is keep=False

        self.assertEqual(j_cols["EmpID"]["sources"], [("l_in", "ID")])
        self.assertEqual(j_cols["EmpName"]["sources"], [("l_in", "Name")])
        self.assertEqual(j_cols["AnnualSalary"]["sources"], [("r_in", "Salary")])

        # Downstream impact of left ID vs left Dept
        impact_id = compute_downstream_impact(workflow, "l_in", "ID")
        self.assertIn("j", impact_id["impacted_node_ids"])

        impact_dept = compute_downstream_impact(workflow, "l_in", "Dept")
        # Dept is connected to j, but dropped in embedded select
        self.assertIn("j", impact_dept["impacted_node_ids"])

