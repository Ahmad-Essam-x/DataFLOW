    def test_end_to_end_multi_tool_lineage_pipeline(self):
        """
        Deep multi-tool pipeline test:
        input -> multi_row_formula -> text_to_columns -> summarize -> select -> formula -> filter
        Verifies schema propagation, *Unknown filtering, and full backward provenance chain.
        """
        workflow = {
            "nodes": [
                {"id": "n1", "name": "Orders", "type": "input_data", "config": {"columns": ["OrderID", "CustomerInfo", "Subtotal"]}},
                {
                    "id": "n2",
                    "name": "MRF",
                    "type": "multi_row_formula",
                    "config": {
                        "is_new_field": True,
                        "output_field": "RunningSubtotal",
                        "output_type": "float",
                        "expression": "[Row-1:RunningSubtotal] + [Subtotal]"
                    }
                },
                {
                    "id": "n3",
                    "name": "TTC",
                    "type": "text_to_columns",
                    "config": {
                        "column": "CustomerInfo",
                        "num_columns": 2,
                        "root_name": "Cust"
                    }
                },
                {
                    "id": "n4",
                    "name": "Summarize",
                    "type": "summarize",
                    "config": {
                        "actions": [
                            {"field": "Cust1", "action": "GroupBy", "output_name": "CustName"},
                            {"field": "RunningSubtotal", "action": "Sum", "output_name": "TotalRunning"},
                            {"field": "Subtotal", "action": "Avg", "output_name": "AvgSubtotal"}
                        ]
                    }
                },
                {
                    "id": "n5",
                    "name": "Select",
                    "type": "select",
                    "config": {
                        "fields": [
                            {"original": "CustName", "keep": True, "rename": "Customer"},
                            {"original": "TotalRunning", "keep": True, "rename": "TotalVolume"},
                            {"original": "AvgSubtotal", "keep": False},
                            {"original": "*Unknown", "keep": False}
                        ]
                    }
                },
                {
                    "id": "n6",
                    "name": "Formula",
                    "type": "formula",
                    "config": {
                        "formulas": [
                            {"output_field": "IsHighVolume", "type": "bool", "expression": "[TotalVolume] > 1000"}
                        ]
                    }
                },
                {
                    "id": "n7",
                    "name": "Filter",
                    "type": "filter",
                    "config": {
                        "filter_type": "basic",
                        "field": "IsHighVolume",
                        "operator": "is_true"
                    }
                }
            ],
            "connections": [
                {"source": "n1", "target": "n2"},
                {"source": "n2", "target": "n3"},
                {"source": "n3", "target": "n4"},
                {"source": "n4", "target": "n5"},
                {"source": "n5", "target": "n6"},
                {"source": "n6", "target": "n7"}
            ]
        }

        rich = compute_rich_lineage(workflow)
        # Check end of pipeline: n7
        self.assertIn("Customer", rich["n7"])
        self.assertIn("TotalVolume", rich["n7"])
        self.assertIn("IsHighVolume", rich["n7"])
        self.assertNotIn("AvgSubtotal", rich["n7"])

        # Customer traces to n1 CustomerInfo
        self.assertEqual(rich["n7"]["Customer"]["sources"], [("n1", "CustomerInfo")])
        # TotalVolume traces to n1 Subtotal (via MRF RunningSubtotal and Summarize TotalRunning)
        self.assertIn(("n1", "Subtotal"), rich["n7"]["TotalVolume"]["sources"])
        # IsHighVolume traces to TotalVolume which traces to n1 Subtotal
        self.assertIn(("n1", "Subtotal"), rich["n7"]["IsHighVolume"]["sources"])

        # Downstream impact of Subtotal reaches n2, n4, n5, n6, n7
        impact = compute_downstream_impact(workflow, "n1", "Subtotal")
        for expected_nid in ["n2", "n4", "n5", "n6", "n7"]:
            self.assertIn(expected_nid, impact["impacted_node_ids"])


