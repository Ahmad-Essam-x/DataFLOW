"""
Build script for the Antigravity DataFlow Windows desktop app (PyInstaller, onedir).

  py build_desktop.py            # build dist/AntigravityDataFlow/ and the portable zip
  py build_desktop.py --no-clean # reuse PyInstaller's cache

Release content is staged from files tracked by git, never from the working folder. That keeps customer
workflows, uploaded data, caches, backups and autosaves out of the shipped app.
"""
import argparse
import os
import shutil
import subprocess
import sys
import time

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from backend._version import APP_NAME, __version__
from desktop.assets import generate_app_icon

EXE_NAME = "AntigravityDataFlow"

# Folders shipped read-only inside the app (user data is created under %LOCALAPPDATA% on first run).
PAYLOAD_DIRS = ("static", "templates", "data", "workflows", "assets")

HIDDEN_IMPORTS = [
    "waitress", "flask", "jinja2", "werkzeug", "werkzeug.serving",
    "openpyxl", "openpyxl.cell._writer", "python_calamine",
    "pandas", "numpy", "pyarrow", "pyarrow.feather", "duckdb",
    "pydantic", "requests", "psutil", "PIL",
    "keyring", "keyring.backends.Windows",
    "webview", "webview.platforms.winforms", "pythonnet", "clr_loader",
    "desktop.diagnostics", "desktop.shortcuts", "desktop.assets",
]

# Node modules are imported by name at startup; make sure PyInstaller bundles every one of them.
from backend.engine.nodes.registry import NODE_MODULES  # noqa: E402
HIDDEN_IMPORTS += [f"backend.engine.nodes.{m}" for m in NODE_MODULES]

# Large scientific/UI stacks the app does not use (PyInstaller would otherwise pull them in from Anaconda).
EXCLUDES = [
    "scipy", "matplotlib", "skimage", "plotly", "bokeh", "seaborn", "statsmodels", "tables", "h5py",
    "notebook", "nbconvert", "nbformat", "IPython", "ipykernel", "jupyter", "jupyter_client", "jupyter_core",
    "cv2", "torch", "torchvision", "torchaudio", "tensorflow", "keras",
    "PyQt5", "PyQt6", "PySide2", "PySide6", "tkinter", "turtle",
    "docutils", "sphinx", "sympy", "pytest", "shapely", "patsy",
    # optional database connectors are loaded lazily; the portable build ships without them
    "snowflake", "psycopg2", "sqlalchemy",
    # test suites bundled inside third-party packages (--collect-all would otherwise include them)
    "pyarrow.tests", "pandas.tests", "numpy.tests",
]


# The workflows/ folder holds the author's scratch, test and customer-case files next to the curated samples.
# Only these are shipped: the flagship workflows (also regenerated by backend/samples/generator.py) and the
# curated templates folder. Anything else would appear in every user's Open dialog.
RELEASE_WORKFLOWS = frozenset({
    "workflows/sales_customer_enrichment.json",
    "workflows/inventory_supplier_reconciliation.json",
    "workflows/marketing_campaign_attribution.json",
    "workflows/multijoin_expense_reconciliation.json",
})


def _ships(rel):
    rel = rel.replace("\\", "/")
    if rel.startswith("workflows/"):
        if rel.startswith("workflows/templates/"):
            return not rel.startswith("workflows/templates/user/")
        return rel in RELEASE_WORKFLOWS
    return True


def stage_payload(stage_dir):
    """Copies release files under PAYLOAD_DIRS (tracked by git, filtered by _ships) into stage_dir."""
    if os.path.exists(stage_dir):
        shutil.rmtree(stage_dir)
    out = subprocess.run(["git", "ls-files", "-z", "--", *PAYLOAD_DIRS], cwd=BASE_DIR,
                         capture_output=True, check=True).stdout.decode("utf-8")
    files = [f for f in out.split("\0") if f and _ships(f)]
    for rel in files:
        src = os.path.join(BASE_DIR, rel)
        if not os.path.isfile(src):
            continue  # deleted but not yet committed
        dst = os.path.join(stage_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
    return len(files)


def write_version_file(path):
    """Windows version resource so Explorer/installer show the real product version."""
    parts = (__version__.split(".") + ["0", "0", "0"])[:4]
    nums = ", ".join(p if p.isdigit() else "0" for p in parts)
    dotted = ".".join(p if p.isdigit() else "0" for p in parts)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"""VSVersionInfo(
  ffi=FixedFileInfo(filevers=({nums}), prodvers=({nums}), mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', ''),
      StringStruct('FileDescription', '{APP_NAME}'),
      StringStruct('FileVersion', '{dotted}'),
      StringStruct('InternalName', '{EXE_NAME}'),
      StringStruct('OriginalFilename', '{EXE_NAME}.exe'),
      StringStruct('ProductName', '{APP_NAME}'),
      StringStruct('ProductVersion', '{dotted}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""")


def build_executable(clean=True):
    print("=" * 56)
    print(f"  {APP_NAME} {__version__} - desktop build (onedir)")
    print("=" * 56)

    # The icon is a tracked asset: only generate it when missing, so builds do not modify the repository.
    ico_path = os.path.join(BASE_DIR, "assets", "icon.ico")
    if not os.path.exists(ico_path):
        ico_path, _png = generate_app_icon(
            output_dir=os.path.join(BASE_DIR, "assets"),
            static_dir=os.path.join(BASE_DIR, "static"),
        )

    build_dir = os.path.join(BASE_DIR, "build")
    dist_dir = os.path.join(BASE_DIR, "dist")
    if clean and os.path.exists(build_dir):
        shutil.rmtree(build_dir, ignore_errors=True)
    os.makedirs(build_dir, exist_ok=True)

    stage_dir = os.path.join(build_dir, "payload")
    count = stage_payload(stage_dir)
    print(f"[INFO] Staged {count} tracked files from {', '.join(PAYLOAD_DIRS)}")

    version_file = os.path.join(build_dir, "version_info.txt")
    write_version_file(version_file)

    cmd = [
        sys.executable, "-m", "PyInstaller", os.path.join(BASE_DIR, "desktop_app.py"),
        f"--name={EXE_NAME}", f"--icon={ico_path}", f"--version-file={version_file}",
        "--windowed", "--noconfirm", "--onedir", "--noupx",
        f"--distpath={dist_dir}", f"--workpath={os.path.join(build_dir, 'pyi')}", f"--specpath={build_dir}",
    ]
    for d in PAYLOAD_DIRS:
        if os.path.isdir(os.path.join(stage_dir, d)):
            cmd += ["--add-data", f"{os.path.join(stage_dir, d)}{os.pathsep}{d}"]
    for h in HIDDEN_IMPORTS:
        cmd += ["--hidden-import", h]
    for ex in EXCLUDES:
        cmd += ["--exclude-module", ex]
    for pkg in ("webview", "pyarrow", "duckdb"):
        cmd += ["--collect-all", pkg]

    start = time.time()
    if subprocess.run(cmd, cwd=BASE_DIR).returncode != 0:
        print("[ERROR] PyInstaller failed.")
        return None

    app_dir = os.path.join(dist_dir, EXE_NAME)
    exe_path = os.path.join(app_dir, f"{EXE_NAME}.exe")
    if not os.path.exists(exe_path):
        print(f"[ERROR] Expected executable not found: {exe_path}")
        return None

    for name in ("Diagnose_DataFlow.bat", "DISTRIBUTION_GUIDE.md", "CHANGELOG.md"):
        src = os.path.join(BASE_DIR, name)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(app_dir, name))

    zip_base = os.path.join(dist_dir, f"{EXE_NAME}_{__version__}_Windows_x64")
    shutil.make_archive(zip_base, "zip", dist_dir, EXE_NAME)
    write_sha256(f"{zip_base}.zip")
    print(f"[OK] Built in {time.time() - start:.0f}s: {exe_path}")
    print(f"[OK] Portable zip: {zip_base}.zip (+ .sha256)")
    return exe_path


def write_sha256(path):
    """Writes <path>.sha256 containing the hex digest, for users to verify downloads."""
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    with open(path + ".sha256", "w", encoding="ascii") as fh:
        fh.write(h.hexdigest() + "\n")
    return h.hexdigest()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=f"{APP_NAME} desktop bundler")
    parser.add_argument("--no-clean", action="store_true", help="Reuse PyInstaller's build cache")
    args = parser.parse_args()
    sys.exit(0 if build_executable(clean=not args.no_clean) else 1)
